package com.it.arithmeticoperator;

public class arithmeticdemo2 {
    //结论：
    //1.整数参与计算，结果只能得到整数
    //2.小数参与计算，结果有可能是不精确的。
    public static void main(String[] args) {
        //除法
        System.out.println(10/2);
        System.out.println(10/3);
        System.out.println(10.0/3);

        //取模
        System.out.println(10%2);
        System.out.println(10%3);

    }
}
